#!/usr/bin/env bash
# Install hermes-agent-harness for the current user. Idempotent; re-run after `git pull`.
#
#   ./install.sh            install / update
#   ./install.sh --dry-run  print what would change
#
# What it does:
#   1. ~/.local/bin/harness and ~/.local/bin/harness-hook shims (run from this checkout)
#   2. copies the Hermes skills (harness, harness-worker) into ~/.hermes/skills/software-factory/
#   3. creates two dedicated Hermes profiles (if missing), cloned from your active profile:
#        harness-coder   Hermes as a coding engine; gets the guard + verify shell hooks
#        harness-worker  kanban card operator (kanban mode only)
#      Your default profile is never modified.
set -euo pipefail

DRY=0; [[ "${1:-}" == "--dry-run" ]] && DRY=1
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN="${HOME}/.local/bin"
HERMES_HOME_DIR="${HERMES_HOME:-$HOME/.hermes}"
SKILLS_DIR="${HERMES_HOME_DIR}/skills/software-factory"

run() { if (( DRY )); then echo "[dry-run] $*"; else "$@"; fi; }
say() { echo "==> $*"; }

# ---- python >= 3.11 ------------------------------------------------------------------------
PY=""
for c in python3.13 python3.12 python3.11 python3; do
  if command -v "$c" >/dev/null 2>&1 && "$c" -c 'import sys; sys.exit(sys.version_info < (3, 11))'; then
    PY="$(command -v "$c")"; break
  fi
done
[[ -n "$PY" ]] || { echo "error: Python 3.11+ not found on PATH" >&2; exit 1; }
say "python: $PY"

# ---- shims ---------------------------------------------------------------------------------
write_shim() {  # write_shim <name> <python module and args>
  local path="$BIN/$1"; shift
  local body="#!/bin/sh
# generated by hermes-agent-harness/install.sh
PYTHONPATH=\"$REPO\${PYTHONPATH:+:\$PYTHONPATH}\" exec \"$PY\" -m $* \"\$@\""
  if (( DRY )); then echo "[dry-run] write $path"; return; fi
  mkdir -p "$BIN"; printf '%s\n' "$body" >"$path"; chmod +x "$path"
}
say "shims in $BIN"
write_shim harness harness
write_shim harness-hook harness.hooks_adapters
case ":$PATH:" in *":$BIN:"*) ;; *) echo "    note: add $BIN to PATH";; esac

# ---- skills --------------------------------------------------------------------------------
say "skills -> $SKILLS_DIR"
for s in "$REPO"/hermes/skills/*/; do
  name="$(basename "$s")"
  run mkdir -p "$SKILLS_DIR/$name"
  run cp -R "$s". "$SKILLS_DIR/$name/"
done

# ---- profiles ------------------------------------------------------------------------------
if ! command -v hermes >/dev/null 2>&1; then
  echo "    hermes CLI not found: skipping profiles (pipeline mode still works)"; exit 0
fi
existing="$(hermes profile list 2>/dev/null || true)"
make_profile() {  # make_profile <name> <description>
  if grep -qw "$1" <<<"$existing"; then echo "    profile $1 exists"; return; fi
  run hermes profile create "$1" --clone --no-alias --description "$2"
}
say "profiles"
make_profile harness-coder "Coding engine for hermes-agent-harness runs (guard + verify hooks)."
make_profile harness-worker "Kanban operator for hermes-agent-harness cards; never edits code."

# Shell hooks for harness-coder: appended once, marked so re-runs do not duplicate them.
CODER_CFG="$HERMES_HOME_DIR/profiles/harness-coder/config.yaml"
MARK="# >>> hermes-agent-harness hooks"
if (( DRY )); then
  echo "[dry-run] add hooks block to $CODER_CFG"
elif [[ -f "$CODER_CFG" ]] && grep -qF "$MARK" "$CODER_CFG"; then
  echo "    hooks already present in $CODER_CFG"
elif [[ -f "$CODER_CFG" ]] && grep -qE '^hooks:' "$CODER_CFG"; then
  echo "    WARNING: $CODER_CFG already has a hooks: block; add these entries by hand:"
  echo "      pre_tool_call: command \"$BIN/harness-hook hermes\", fail_closed: true"
  echo "      pre_verify:    command \"$PY $REPO/hermes/hooks/verify_nudge.py\""
else
  cat >>"$CODER_CFG" <<EOF

$MARK
# Guard every tool call (CONTRACT.md §8); fail closed if the guard itself breaks.
hooks:
  pre_tool_call:
    - matcher: ".*"
      command: "$BIN/harness-hook hermes"
      timeout: 20
      fail_closed: true
  pre_verify:
    - command: "$PY $REPO/hermes/hooks/verify_nudge.py"
      timeout: 10
# <<< hermes-agent-harness hooks
EOF
  echo "    hooks added to $CODER_CFG"
fi

say "done. Next: harness doctor"
